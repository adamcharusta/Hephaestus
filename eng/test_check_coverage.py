import contextlib
import io
import tempfile
import unittest
from pathlib import Path

import importlib.util

SPEC = importlib.util.spec_from_file_location("check_coverage", Path(__file__).with_name("check-coverage.py"))
check_coverage = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(check_coverage)


def report(root: Path, name: str, classes: dict[str, list[tuple[int, int]]], package: str = "Hephaestus.Core") -> Path:
    """Write a Cobertura file: `classes` maps a source file to (line number, hits) pairs."""
    body = "".join(
        f'<class name="C{index}" filename="{root / filename}"><lines>'
        + "".join(f'<line number="{number}" hits="{hits}"/>' for number, hits in lines)
        + "</lines></class>"
        for index, (filename, lines) in enumerate(classes.items())
    )
    path = root / name
    path.write_text(f'<coverage><packages><package name="{package}"><classes>{body}</classes></package></packages></coverage>')
    return path


class CheckCoverage(unittest.TestCase):
    def setUp(self):
        self._directory = tempfile.TemporaryDirectory()
        self.root = Path(self._directory.name)
        self.addCleanup(self._directory.cleanup)
        self.exclusions = self.root / "exclusions.txt"
        self.exclusions.write_text("# none\n")

    def run_gate(self, *extra: str) -> tuple[int, str, str]:
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = check_coverage.main([*extra, "--root", str(self.root), "--exclusions", str(self.exclusions)])
        return code, out.getvalue(), err.getvalue()

    def test_passes_at_or_above_the_threshold(self):
        path = report(self.root, "a.cobertura.xml", {"src/A.cs": [(1, 1), (2, 1), (3, 1), (4, 1), (5, 0)]})
        code, out, _ = self.run_gate(str(path))
        self.assertEqual(code, 0)
        self.assertIn("80.00%", out)

    def test_fails_below_the_threshold(self):
        path = report(self.root, "a.cobertura.xml", {"src/A.cs": [(1, 1), (2, 1), (3, 1), (4, 0), (5, 0)]})
        code, _, err = self.run_gate(str(path))
        self.assertEqual(code, 1)
        self.assertIn("below 80%", err)

    def test_threshold_is_configurable(self):
        path = report(self.root, "a.cobertura.xml", {"src/A.cs": [(1, 1), (2, 0)]})
        self.assertEqual(self.run_gate(str(path), "--threshold", "50")[0], 0)
        self.assertEqual(self.run_gate(str(path), "--threshold", "51")[0], 1)

    def test_a_line_covered_by_any_report_counts_as_covered(self):
        first = report(self.root, "a.cobertura.xml", {"src/A.cs": [(1, 1), (2, 0)]})
        second = report(self.root, "b.cobertura.xml", {"src/A.cs": [(1, 0), (2, 3)]})
        code, out, _ = self.run_gate(str(first), str(second), "--threshold", "100")
        self.assertEqual(code, 0)
        self.assertIn("(2/2 lines", out)

    def test_a_directory_is_searched_for_reports(self):
        report(self.root, "a.cobertura.123.xml", {"src/A.cs": [(1, 1)]})
        self.assertEqual(self.run_gate(str(self.root))[0], 0)

    def test_an_excluded_file_is_left_out_and_named(self):
        self.exclusions.write_text("src/Generated/**  # generated by a tool\n")
        path = report(self.root, "a.cobertura.xml", {"src/A.cs": [(1, 1)], "src/Generated/G.cs": [(1, 0), (2, 0)]})
        code, out, _ = self.run_gate(str(path))
        self.assertEqual(code, 0)
        self.assertIn("excluded: src/Generated/G.cs", out)
        self.assertIn("100.00%", out)

    def test_an_exclusion_without_a_reason_fails(self):
        self.exclusions.write_text("src/Generated/**\n")
        path = report(self.root, "a.cobertura.xml", {"src/A.cs": [(1, 1)]})
        code, _, err = self.run_gate(str(path))
        self.assertEqual(code, 2)
        self.assertIn("has no reason", err)

    def test_an_exclusion_with_an_empty_reason_fails(self):
        self.exclusions.write_text("src/Generated/**  #   \n")
        path = report(self.root, "a.cobertura.xml", {"src/A.cs": [(1, 1)]})
        self.assertEqual(self.run_gate(str(path))[0], 2)

    def test_no_coverable_lines_passes_with_a_notice(self):
        path = report(self.root, "a.cobertura.xml", {})
        code, out, _ = self.run_gate(str(path))
        self.assertEqual(code, 0)
        self.assertIn("no coverable lines", out)

    def test_a_required_package_missing_from_the_reports_fails(self):
        path = report(self.root, "a.cobertura.xml", {})
        code, _, err = self.run_gate(str(path), "--require-package", "Hephaestus.Core", "--require-package", "Hephaestus.Host")
        self.assertEqual(code, 2)
        self.assertIn("Hephaestus.Host", err)
        self.assertNotIn("Hephaestus.Core,", err)

    def test_every_project_under_src_must_appear_in_the_reports(self):
        (self.root / "src" / "Hephaestus.Core").mkdir(parents=True)
        (self.root / "src" / "Hephaestus.Core" / "Hephaestus.Core.csproj").write_text("<Project />")
        (self.root / "src" / "Hephaestus.Host").mkdir(parents=True)
        (self.root / "src" / "Hephaestus.Host" / "Hephaestus.Host.csproj").write_text("<Project />")
        (self.root / "src" / "Dashboard").mkdir()
        path = report(self.root, "a.cobertura.xml", {})
        code, _, err = self.run_gate(str(path))
        self.assertEqual(code, 2)
        self.assertIn("Hephaestus.Host", err)
        self.assertNotIn("Dashboard", err)

    def test_a_malformed_report_fails_with_a_message(self):
        broken = self.root / "a.cobertura.xml"
        broken.write_text("<coverage><packages>")
        code, _, err = self.run_gate(str(broken))
        self.assertEqual(code, 2)
        self.assertIn("not a readable Cobertura file", err)

    def test_a_windows_path_in_a_report_matches_a_glob(self):
        self.exclusions.write_text("src/Generated/**  # generated\n")
        body = '<class name="C" filename="src\\Generated\\G.cs"><lines><line number="1" hits="0"/></lines></class>'
        path = self.root / "a.cobertura.xml"
        path.write_text(f'<coverage><packages><package name="P"><classes>{body}</classes></package></packages></coverage>')
        code, out, _ = self.run_gate(str(path))
        self.assertEqual(code, 0)
        self.assertIn("excluded: src/Generated/G.cs", out)

    def test_no_report_fails(self):
        code, _, err = self.run_gate(str(self.root))
        self.assertEqual(code, 2)
        self.assertIn("no Cobertura report", err)

    def test_a_mistyped_report_path_fails_instead_of_being_skipped(self):
        good = report(self.root, "a.cobertura.xml", {"src/A.cs": [(1, 1)]})
        code, _, err = self.run_gate(str(good), str(self.root / "typo.xml"))
        self.assertEqual(code, 2)
        self.assertIn("typo.xml: no such file or directory", err)

    def test_a_missing_exclusions_file_fails(self):
        self.exclusions.unlink()
        path = report(self.root, "a.cobertura.xml", {"src/A.cs": [(1, 1)]})
        self.assertEqual(self.run_gate(str(path))[0], 2)


class RelativePaths(unittest.TestCase):
    def test_an_absolute_path_under_the_root_is_made_relative(self):
        self.assertEqual(check_coverage.relative_path("/repo/src/A.cs", Path("/repo")), "src/A.cs")

    def test_a_path_with_its_leading_slash_stripped_is_made_relative(self):
        self.assertEqual(check_coverage.relative_path("repo/src/A.cs", Path("/repo")), "src/A.cs")

    def test_a_relative_path_is_kept(self):
        self.assertEqual(check_coverage.relative_path("src/A.cs", Path("/repo")), "src/A.cs")

    def test_a_path_outside_the_root_is_kept_and_backslashes_become_slashes(self):
        self.assertEqual(check_coverage.relative_path("C:\\other\\A.cs", Path("/repo")), "C:/other/A.cs")

    def test_a_sibling_directory_with_the_same_prefix_is_not_inside_the_root(self):
        self.assertEqual(check_coverage.relative_path("/repository/src/A.cs", Path("/repo")), "/repository/src/A.cs")


class Globs(unittest.TestCase):
    def matches(self, pattern: str, path: str) -> bool:
        return check_coverage.glob_to_regex(pattern).match(path) is not None

    def test_star_stays_inside_a_directory(self):
        self.assertTrue(self.matches("src/*.cs", "src/A.cs"))
        self.assertFalse(self.matches("src/*.cs", "src/x/A.cs"))

    def test_double_star_crosses_directories(self):
        self.assertTrue(self.matches("src/**/A.cs", "src/A.cs"))
        self.assertTrue(self.matches("src/**/A.cs", "src/x/y/A.cs"))
        self.assertTrue(self.matches("src/Generated/**", "src/Generated/x/G.cs"))

    def test_question_mark_is_one_character(self):
        self.assertTrue(self.matches("src/?.cs", "src/A.cs"))
        self.assertFalse(self.matches("src/?.cs", "src/AB.cs"))

    def test_a_dot_is_literal(self):
        self.assertFalse(self.matches("src/A.cs", "src/AxCs"))


if __name__ == "__main__":
    unittest.main()
